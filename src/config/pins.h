// ============================================================================
// NEON REQUIEM — Pin Definitions
// ============================================================================
// Полная распиновка ESP32-S3-WROOM N16R8 для NEON REQUIEM.
// Все пины вынесены в отдельный заголовок для удобства адаптации под
// другие платы или изменения конфигурации.
// ============================================================================

#ifndef NEON_REQUIEM_PINS_H
#define NEON_REQUIEM_PINS_H

#include <cstdint>

// ============================================================================
// ДИСПЛЕЙ — TFT ST7789 2.0" 320x240 (SPI)
// ============================================================================
// Используется библиотека TFT_eSPI. Пины задаются вручную, т.к. стандартный
// конфиг TFT_eSPI может не совпадать с нашей распиновкой.

/// SPI MOSI — данные от ESP к дисплею
constexpr uint8_t PIN_TFT_MOSI  = 11;

/// SPI SCK — тактовый сигнал
constexpr uint8_t PIN_TFT_SCLK  = 12;

/// Chip Select — выбор дисплея на шине SPI
constexpr uint8_t PIN_TFT_CS    = 10;

/// Data/Command — переключение между данными и командами
constexpr uint8_t PIN_TFT_DC    = 9;

/// Reset — аппаратный сброс дисплея
constexpr uint8_t PIN_TFT_RST   = 8;

/// Backlight — управление подсветкой (PWM)
constexpr uint8_t PIN_TFT_BL    = 7;

// ============================================================================
// УПРАВЛЕНИЕ — D-Pad + Кнопки (GPIO, pull-up)
// ============================================================================
// Все кнопки подтянуты к GND через внешние резисторы 10kΩ.
// Состояние: LOW = нажата, HIGH = отпущена.
// Используем GPIO с поддержкой прерываний для точного ввода.

/// D-Pad: Вверх
constexpr uint8_t PIN_BTN_UP     = 1;

/// D-Pad: Вниз
constexpr uint8_t PIN_BTN_DOWN   = 2;

/// D-Pad: Влево
constexpr uint8_t PIN_BTN_LEFT   = 3;

/// D-Pad: Вправо
constexpr uint8_t PIN_BTN_RIGHT  = 4;

/// Кнопка A (действие/подтверждение)
constexpr uint8_t PIN_BTN_A      = 5;

/// Кнопка B (отмена/RESONANCE)
constexpr uint8_t PIN_BTN_B      = 6;

/// Кнопка START (пауза/меню)
constexpr uint8_t PIN_BTN_START  = 15;

/// Кнопка SELECT (карта/квесты)
constexpr uint8_t PIN_BTN_SELECT = 16;

// ============================================================================
// ЗВУК — I2S MAX98357A
// ============================================================================
// Усилитель MAX98357A подключается по I2S-протоколу.
// Поддерживает только вывод (TX), микрофона нет.

/// I2S Bit Clock — тактовый сигнал
constexpr uint8_t PIN_I2S_BCLK   = 17;

/// I2S Left/Right Clock — выбор канала (Word Select)
constexpr uint8_t PIN_I2S_LRC    = 18;

/// I2S Data Out — аудиоданные к усилителю
constexpr uint8_t PIN_I2S_DOUT   = 14;

// ============================================================================
// SD-КАРТА — SPI Mode
// ============================================================================
// SD-карта работает в SPI-режиме. MOSI и SCK разделяются с дисплеем,
// но CS у SD-карты отдельный — это позволяет работать обоим устройствам
// на одной шине SPI.

/// SPI MOSI (общий с дисплеем)
constexpr uint8_t PIN_SD_MOSI    = 11;

/// SPI MISO — данные от SD к ESP
constexpr uint8_t PIN_SD_MISO    = 13;

/// SPI SCK (общий с дисплеем)
constexpr uint8_t PIN_SD_SCLK    = 12;

/// Chip Select — выбор SD-карты
constexpr uint8_t PIN_SD_CS      = 21;

// ============================================================================
// ПИТАНИЕ
// ============================================================================

/// ADC для измерения напряжения батареи (через делитель)
constexpr uint8_t PIN_BATTERY    = 4;

/// Удержание питания (GPIO, который держит MOSFET включённым)
constexpr uint8_t PIN_POWER_HOLD = 48;

// ============================================================================
// ДОПОЛНИТЕЛЬНЫЕ ПИНЫ (резерв)
// ============================================================================

/// Светодиод статуса (встроенный на некоторых платах)
constexpr uint8_t PIN_LED_BUILTIN = 38;

// ============================================================================
// SPI БИБЛИОТЕКА — Настройки шины
// ============================================================================
// ESP32-S3 имеет несколько SPI-контроллеров. Используем HSPI для дисплея
// и SD-карты, чтобы не конфликтовать с другими периферийными устройствами.

/// Номер SPI-контроллера для дисплея и SD
#define SPI_BUS_HOST            SPI2_HOST

/// Частота SPI для SD-карты (ниже, чем у дисплея — SD менее стабильна на
/// высоких частотах)
constexpr int SD_SPI_FREQ       = 20000000;  // 20 MHz

// ============================================================================
// МАСКИ ДЛЯ БЫСТРОЙ ОБРАБОТКИ ВВОДА
// ============================================================================
// Используются в InputManager для побитовой обработки состояний кнопок.
// Это позволяет обрабатывать весь ввод за одну операцию чтения GPIO.

/// Битовая маска для D-Pad
constexpr uint32_t MASK_DPAD = (1ULL << PIN_BTN_UP)    |
                               (1ULL << PIN_BTN_DOWN)  |
                               (1ULL << PIN_BTN_LEFT)  |
                               (1ULL << PIN_BTN_RIGHT);

/// Битовая маска для кнопок действий
constexpr uint32_t MASK_ACTION = (1ULL << PIN_BTN_A)      |
                                 (1ULL << PIN_BTN_B)      |
                                 (1ULL << PIN_BTN_START)  |
                                 (1ULL << PIN_BTN_SELECT);

/// Полная маска всех кнопок
constexpr uint32_t MASK_ALL_BUTTONS = MASK_DPAD | MASK_ACTION;

// ============================================================================
// ПРОВЕРКА КОНФЛИКТОВ ПИНОВ
// ============================================================================
// Компилятор проверит, что нет пересечений пинов между устройствами.
// Если возникнет ошибка — значит распиновка сконфигурирована неверно.

static_assert(PIN_TFT_MOSI != PIN_SD_MISO, "MOSI and MISO cannot share the same pin");
static_assert(PIN_TFT_CS   != PIN_SD_CS,   "TFT CS and SD CS must be different pins");
static_assert(PIN_TFT_DC   != PIN_TFT_CS,  "DC and CS must be different pins");

#endif // NEON_REQUIEM_PINS_H